create table if not exists public.admin_users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text not null,
  first_admin_lock boolean not null default true unique,
  created_at timestamptz not null default now()
);
create table if not exists public.partners (
  id bigint generated by default as identity primary key,
  name varchar(80) not null,
  slug varchar(40) not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  name varchar(120) not null,
  contact varchar(190) not null,
  source varchar(200), visitor_id varchar(80), ref varchar(80),
  utm_source varchar(80), utm_medium varchar(80), utm_campaign varchar(80), utm_content varchar(80), utm_term varchar(80),
  created_at timestamptz not null default now()
);
create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  source varchar(80), plan varchar(30) not null default 'other', amount numeric(12,2) not null default 0,
  comment varchar(300), paid_at date not null default current_date, lead_id bigint, created_at timestamptz not null default now()
);
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  visitor_id varchar(80), session_id varchar(80), event varchar(40) not null, plan varchar(30), click_id varchar(40), ref varchar(80),
  utm_source varchar(80), utm_medium varchar(80), utm_campaign varchar(80), utm_content varchar(80), utm_term varchar(80),
  path varchar(200), referrer varchar(200), meta jsonb, created_at timestamptz not null default now()
);
-- Безопасность: клиентскому anon key доступ к таблицам не предоставляем. Function использует service-role key на сервере.
alter table public.admin_users enable row level security;
alter table public.partners enable row level security;
alter table public.leads enable row level security;
alter table public.payments enable row level security;
alter table public.events enable row level security;
